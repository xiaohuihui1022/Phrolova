// 去重构建 Map（后面的条目覆盖前面的，确保键唯一）
const TRAD_TO_SIMP: Record<string, string> = {};
for (const [k, v] of _TRAD_SIMP_ENTRIES) {
  TRAD_TO_SIMP[k] = v;
}

/**
 * 将繁体中文字符转换为简体中文
 * @param text 输入文本（可包含繁简混合内容）
 * @returns 转换为简体后的文本
 */
export function toSimplified(text: string): string {
  if (!text) return text;
  let result = '';
  let i = 0;
  while (i < text.length) {
    // 先尝试最长匹配的多字词（3 字优先，再 2 字）
    let matched = false;
    for (let len = 3; len >= 2; len--) {
      if (i + len <= text.length) {
        const substr = text.slice(i, i + len);
        if (TRAD_TO_SIMP[substr]) {
          result += TRAD_TO_SIMP[substr];
          i += len;
          matched = true;
          break;
        }
      }
    }
    if (!matched) {
      const char = text[i];
      result += TRAD_TO_SIMP[char] ?? char;
      i++;
    }
  }
  return result;
}

/**
 * 规范化搜索文本：统一转为简体 + 小写
 * 用于搜索时的关键词和被搜索文本预处理，确保繁简兼容检索
 */
export function normalizeSearchText(text: string): string {
  return toSimplified(text).toLowerCase();
}

/**
 * 检查文本是否包含关键词（繁简兼容）
 * @param text 被搜索文本
 * @param keyword 搜索关键词
 */
export function searchIncludes(text: string, keyword: string): boolean {
  const normalizedText = normalizeSearchText(text);
  const normalizedKeyword = normalizeSearchText(keyword.trim());
  if (!normalizedKeyword) return true;
  return normalizedText.includes(normalizedKeyword);
}
